//! Core types for the Auto-Healing Agent neural repair pipeline.
//!
//! The network is a **classifier / selector**, never a code generator.
//! It outputs `operator_id` + confidence + risk; deterministic operators apply the patch.

#![cfg_attr(not(feature = "std"), no_std)]

extern crate alloc;

use alloc::string::String;
use alloc::vec::Vec;
use serde::{Deserialize, Serialize};

/// Fixed operator vocabulary. The NN selects one of these IDs.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[repr(u8)]
pub enum OperatorId {
    NoOp = 0,
    DependencyRepair = 1,
    SyntaxFix = 2,
    ConfigRepair = 3,
    BuildScriptFix = 4,
    EnvVarRepair = 5,
    LockfileRefresh = 6,
    TypeAnnotationFix = 7,
    ImportPathFix = 8,
    VersionPin = 9,
    CacheClear = 10,
    Unknown = 255,
}

impl OperatorId {
    pub fn from_u8(v: u8) -> Self {
        match v {
            0 => Self::NoOp,
            1 => Self::DependencyRepair,
            2 => Self::SyntaxFix,
            3 => Self::ConfigRepair,
            4 => Self::BuildScriptFix,
            5 => Self::EnvVarRepair,
            6 => Self::LockfileRefresh,
            7 => Self::TypeAnnotationFix,
            8 => Self::ImportPathFix,
            9 => Self::VersionPin,
            10 => Self::CacheClear,
            _ => Self::Unknown,
        }
    }

    pub fn as_str(&self) -> &'static str {
        match self {
            Self::NoOp => "NO_OP",
            Self::DependencyRepair => "DEPENDENCY_REPAIR",
            Self::SyntaxFix => "SYNTAX_FIX",
            Self::ConfigRepair => "CONFIG_REPAIR",
            Self::BuildScriptFix => "BUILD_SCRIPT_FIX",
            Self::EnvVarRepair => "ENV_VAR_REPAIR",
            Self::LockfileRefresh => "LOCKFILE_REFRESH",
            Self::TypeAnnotationFix => "TYPE_ANNOTATION_FIX",
            Self::ImportPathFix => "IMPORT_PATH_FIX",
            Self::VersionPin => "VERSION_PIN",
            Self::CacheClear => "CACHE_CLEAR",
            Self::Unknown => "UNKNOWN",
        }
    }
}

/// Normalized incident coming from Vercel / Linear / GitHub Actions.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Incident {
    pub id: String,
    pub source: String,
    pub error_code: String,
    pub error_step: String,
    pub command: String,
    pub message: String,
    pub project: String,
    pub attempts: u32,
    pub stack_hint: String,
    pub language_hint: String,
    pub framework_hint: String,
    pub verified: bool,
    pub status: String,
}

impl Default for Incident {
    fn default() -> Self {
        Self {
            id: String::new(),
            source: String::from("unknown"),
            error_code: String::new(),
            error_step: String::new(),
            command: String::new(),
            message: String::new(),
            project: String::new(),
            attempts: 0,
            stack_hint: String::new(),
            language_hint: String::new(),
            framework_hint: String::new(),
            verified: false,
            status: String::from("open"),
        }
    }
}

/// Output of the neural classifier.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RepairAction {
    pub operator_id: OperatorId,
    pub confidence: f32,
    pub risk: f32,
    /// Optional human-readable rationale (generated by feature engine, not LLM).
    pub rationale: String,
}

impl RepairAction {
    pub fn is_actionable(&self, min_confidence: f32, max_risk: f32) -> bool {
        self.confidence >= min_confidence
            && self.risk <= max_risk
            && self.operator_id != OperatorId::NoOp
            && self.operator_id != OperatorId::Unknown
    }
}

/// Full repair case persisted after verification.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RepairCase {
    pub incident_id: String,
    pub action: RepairAction,
    pub verification: VerificationResult,
    pub patch_summary: String,
    pub pr_url: Option<String>,
    pub created_at_unix: u64,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum VerificationResult {
    Pass,
    Fail,
    Blocked,
    Skipped,
}

/// Fixed-size feature vector (16 dims) consumed by the NN.
#[derive(Debug, Clone, Copy)]
pub struct FeatureVector {
    pub values: [f32; 16],
}

impl FeatureVector {
    pub const DIM: usize = 16;

    pub fn zeros() -> Self {
        Self { values: [0.0; 16] }
    }

    pub fn as_slice(&self) -> &[f32; 16] {
        &self.values
    }
}
